package updatenotice

import (
	"context"
	"encoding/json"
	"io"
	"net"
	"net/http"
	"strings"
	"time"
)

const (
	releaseURL      = "https://api.github.com/repos/openai/openai-cli/releases/latest"
	homebrewCaskURL = "https://api.github.com/repos/openai/homebrew-tools/contents/Casks/openai.rb?ref=main"
	checkTimeout    = 200 * time.Millisecond
	maxReleaseBytes = 256 * 1024
)

// This client uses environment proxies without SDK configuration, API credentials, or redirects.
func releaseClient() *http.Client {
	return &http.Client{
		Timeout:       checkTimeout,
		CheckRedirect: func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse },
		Transport: &http.Transport{
			Proxy:                  http.ProxyFromEnvironment,
			DialContext:            releaseDialer().DialContext,
			TLSHandshakeTimeout:    checkTimeout,
			ResponseHeaderTimeout:  checkTimeout,
			MaxResponseHeaderBytes: 16 * 1024,
			DisableKeepAlives:      true,
		},
	}
}

func releaseDialer() *net.Dialer {
	// Go's default 300ms fallback would outlast the entire discovery deadline.
	return &net.Dialer{Timeout: checkTimeout, FallbackDelay: checkTimeout / 4}
}

func latestRelease(ctx context.Context, client *http.Client) string {
	data := fetchReleaseMetadata(ctx, client, releaseURL, "application/vnd.github+json")
	var release struct {
		Tag        string `json:"tag_name"`
		Draft      *bool  `json:"draft"`
		Prerelease *bool  `json:"prerelease"`
	}
	if json.Unmarshal(data, &release) != nil || release.Draft == nil || *release.Draft || release.Prerelease == nil || *release.Prerelease {
		return ""
	}
	version, _ := stableVersion(release.Tag)
	return version
}

func latestHomebrewRelease(ctx context.Context, client *http.Client) string {
	data := fetchReleaseMetadata(ctx, client, homebrewCaskURL, "application/vnd.github.raw+json")
	// Read only the literal header generated by GoReleaser. Never execute Ruby.
	content := strings.TrimSpace(string(data))
	for strings.HasPrefix(content, "#") {
		_, rest, _ := strings.Cut(content, "\n")
		content = strings.TrimSpace(rest)
	}
	const prefix = "cask \"openai\" do\n  version \""
	body, ok := strings.CutPrefix(content, prefix)
	if !ok || !strings.HasSuffix(body, "\nend") || strings.Contains(body, "\n  version ") {
		return ""
	}
	value, _, ok := strings.Cut(body, "\"\n")
	version, valid := stableVersion(value)
	if !ok || !valid || version != value {
		return ""
	}
	return version
}

func fetchReleaseMetadata(ctx context.Context, client *http.Client, url, accept string) []byte {
	request, err := http.NewRequestWithContext(ctx, http.MethodGet, url, nil)
	if err != nil {
		return nil
	}
	request.Header.Set("Accept", accept)
	request.Header.Set("User-Agent", "openai-cli")
	response, err := client.Do(request)
	if err != nil {
		return nil
	}
	defer response.Body.Close()
	if response.StatusCode != http.StatusOK {
		return nil
	}
	data, err := io.ReadAll(io.LimitReader(response.Body, maxReleaseBytes+1))
	if err != nil || len(data) > maxReleaseBytes || ctx.Err() != nil {
		return nil
	}
	return data
}
