package app

import (
	"fmt"
	"io"
	"strings"

	batchcommands "github.com/openai/openai-cli/internal/commands/batches"
	"github.com/openai/openai-cli/internal/readable"
	"github.com/tidwall/gjson"
)

// Only one recognized, bounded browser projection uses this layout. The stored
// document stays plain text; trusted byte ranges carry optional terminal styles.
func showBatchResultDetail(out io.Writer, value gjson.Result, decorate func(batchcommands.RecordTextStyle)) error {
	w := &batchDetailWriter{out: out, decorate: decorate}
	w.text("identity", strings.TrimSuffix(readableValue(value.Get("request")), "\n"))
	if outcome := value.Get("outcome"); outcome.Type == gjson.String && outcome.Str != "" {
		text := strings.ReplaceAll(outcome.Str, "_", " ")
		w.text("", "  ")
		w.text(batchResultTone(value), strings.ToUpper(text[:1])+text[1:])
	}
	w.text("", "\n")
	value.ForEach(func(key, field gjson.Result) bool {
		if key.Str == "request" || key.Str == "outcome" || key.Str == "usage" {
			return true
		}
		sections := map[string]string{
			"output": "Output", "choices": "Choices", "error": "Error", "error_details": "Error details",
			"refusal": "Refusal", "incomplete_details": "Incomplete details",
		}
		if title, ok := sections[key.Str]; ok {
			w.text("", "\n")
			w.text("heading", title+"\n")
			if w.err == nil {
				w.err = readable.Write(w, field)
			}
		} else {
			role := "secondary"
			if key.Str == "content_outcome" || key.Str == "output_state" {
				role = "warning"
			}
			// Projection keys are generated by the reviewed transformer.
			w.text(role, readableValue(gjson.Parse(fmt.Sprintf("{%q:%s}", key.Str, field.Raw))))
		}
		return w.err == nil
	})
	if usage := value.Get("usage"); usage.Exists() && w.err == nil {
		w.text("", "\n")
		if summary, ok := batchTokenSummary(usage); ok {
			w.text("secondary", summary+"\n")
		} else {
			w.text("heading", "Usage\n")
			w.err = readable.Write(w, usage)
		}
	}
	return w.err
}

func batchResultTone(value gjson.Result) string {
	if err := value.Get("error"); err.Exists() && err.Type != gjson.Null {
		return "negative"
	}
	switch value.Get("outcome").Str {
	case "failed", "request failed":
		return "negative"
	case "incomplete", "incomplete (output limit)", "filtered":
		return "warning"
	case "in_progress", "queued", "tool call returned":
		return "active"
	case "completed":
		for _, key := range []string{"content_outcome", "output_state", "incomplete_details"} {
			if field := value.Get(key); field.Exists() && field.Type != gjson.Null {
				return "warning"
			}
		}
		if output := value.Get("output"); output.Type == gjson.String && output.Str != "" {
			return "positive"
		}
	}
	return ""
}

func batchTokenSummary(value gjson.Result) (string, bool) {
	if !value.IsObject() {
		return "", false
	}
	fields := make(map[string]string)
	valid := true
	value.ForEach(func(key, field gjson.Result) bool {
		if _, duplicate := fields[key.Str]; duplicate || field.Type != gjson.Number || field.Raw == "" {
			valid = false
			return false
		}
		for _, digit := range field.Raw {
			if digit < '0' || digit > '9' {
				valid = false
				return false
			}
		}
		fields[key.Str] = field.Raw
		return true
	})
	if !valid || len(fields) != 3 || fields["total_tokens"] == "" {
		return "", false
	}
	input, output := fields["input_tokens"], fields["output_tokens"]
	if input == "" || output == "" {
		input, output = fields["prompt_tokens"], fields["completion_tokens"]
	}
	if input == "" || output == "" {
		return "", false
	}
	return fmt.Sprintf("Tokens  %s input  %s output  %s total", input, output, fields["total_tokens"]), true
}

func readableValue(value gjson.Result) string {
	var out strings.Builder
	_ = readable.Write(&out, value)
	return out.String()
}

type batchDetailWriter struct {
	out      io.Writer
	decorate func(batchcommands.RecordTextStyle)
	offset   int64
	err      error
}

func (w *batchDetailWriter) Write(data []byte) (int, error) {
	if w.err != nil {
		return 0, w.err
	}
	n, err := w.out.Write(data)
	if err == nil && n != len(data) {
		err = io.ErrShortWrite
	}
	w.offset += int64(n)
	w.err = err
	return n, err
}

func (w *batchDetailWriter) text(role, text string) {
	start := w.offset
	_, _ = io.WriteString(w, text)
	if role != "" && w.offset > start {
		w.decorate(batchcommands.RecordTextStyle{Start: start, End: w.offset, Role: role})
	}
}
